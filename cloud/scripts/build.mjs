// build.mjs — Rokar POS cloud foundation build.
//
//   1. Code-generates src/generated-migrations.ts from the REAL desktop
//      migrations/*.js files (default-import interop, exported as MIGRATIONS).
//   2. Bundles src/index.ts -> dist/index.js with esbuild, applying the only two
//      aliases the whole foundation needs:
//        - "../db"          -> src/web-db.ts     (real services' db singleton)
//        - "(node:)crypto"  -> src/crypto-shim.ts (byte-compatible noble scrypt)
//      The output must be prebuilt because wrangler's own bundler cannot apply
//      these aliases, so wrangler.toml points `main` at dist/index.js.
//
// Desktop code is never edited — everything is adapted in cloud/.
//
// Run: node scripts/build.mjs   (after any `npm install`, also run fix-workerd)

import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const migrationsDir = path.resolve(root, '..', 'migrations');

// The desktop app version, injected as `__APP_VERSION__` so `app:get-version`
// (Settings → About) reports the renderer's REAL version instead of a
// hand-maintained literal that silently goes stale on every release.
const appVersion = JSON.parse(
  readFileSync(path.resolve(root, '..', 'package.json'), 'utf8')
).version;

// ---------------------------------------------------------------------------
// 1. Codegen the migrations module (cloud tsc needs this file to exist, so the
//    typecheck script also runs the build first).
// ---------------------------------------------------------------------------
const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.js') && !f.startsWith('_'))
  .sort();

if (files.length === 0) {
  throw new Error(`No migration files found in ${migrationsDir}`);
}

const generated = [
  '// AUTO-GENERATED by scripts/build.mjs — do not edit by hand.',
  '// @ts-nocheck — cloud tsc must never follow into desktop migration code;',
  '// esbuild bundles the real migration files at build time.',
  '',
  ...files.map((f, i) => `import m${i} from '../../migrations/${f}';`),
  '',
  'export interface MigrationEntry {',
  '  file: string;',
  '  up: (db: import("./sqlite-compat").SqliteCompat) => unknown | Promise<unknown>;',
  '}',
  '',
  'export const MIGRATIONS: MigrationEntry[] = [',
  ...files.map((f, i) => `  { file: '${f}', up: (db) => m${i}.up(db) },`),
  '];',
  '',
].join('\n');

writeFileSync(path.join(srcDir, 'generated-migrations.ts'), generated, 'utf8');
console.log(`[build] codegen ${files.length} migrations -> src/generated-migrations.ts`);

// ---------------------------------------------------------------------------
// 1b. Codegen the web dashboard assets so the worker bundle stays single-file.
//     src/web.ts serves these three strings (see src/generated-web.ts).
// ---------------------------------------------------------------------------
const webDir = path.join(srcDir, 'web');
const webAssets = {
  APP_HTML: readFileSync(path.join(webDir, 'app.html'), 'utf8'),
  APP_JS: readFileSync(path.join(webDir, 'app.js'), 'utf8'),
  APP_CSS: readFileSync(path.join(webDir, 'style.css'), 'utf8'),
};
const generatedWeb = [
  '// AUTO-GENERATED by scripts/build.mjs — do not edit by hand.',
  ...Object.entries(webAssets).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`),
  '',
].join('\n');
writeFileSync(path.join(srcDir, 'generated-web.ts'), generatedWeb, 'utf8');
console.log('[build] codegen web assets -> src/generated-web.ts');

// ---------------------------------------------------------------------------
// 1c. Alias table for the esbuild plugin below.
//
//     The worker bundles the REAL desktop `src/main/ipc.ts` (via the opaque
//     `@desktop/ipc` specifier), so every POS service is pulled in. The aliases
//     redirect the desktop's db/crypto singletons to cloud shims and replace the
//     Electron/Node-only leaves with inert modules (src/shims/*). First match wins.
// ---------------------------------------------------------------------------
const desktopDir = path.resolve(root, '..', 'src', 'main');
const shim = (name) => path.join(srcDir, 'shims', name);

const resolveAliases = [
  // Real services import { getDb } from '../db' -> cloud web-db singleton.
  { filter: /^\.\.\/db$/, path: path.join(srcDir, 'web-db.ts') },
  // Services + migrations import node:crypto / crypto -> noble scrypt shim.
  { filter: /^(node:)?crypto$/, path: path.join(srcDir, 'crypto-shim.ts') },
  // The REAL desktop IPC surface, imported through opaque specifiers so cloud tsc
  // keeps a thin type boundary and never follows into the Electron/service graph.
  { filter: /^@desktop\/ipc$/, path: path.join(desktopDir, 'ipc.ts') },
  { filter: /^@desktop\/licensing$/, path: path.join(desktopDir, 'services', 'licensing.ts') },
  // Print builders for the web print bridge (web printing: see src/print-bridge.ts).
  { filter: /^@desktop\/print$/, path: path.join(desktopDir, 'services', 'printing.ts') },
  { filter: /^@desktop\/printdocs$/, path: path.join(desktopDir, 'services', 'printDocs.ts') },
  { filter: /^@desktop\/labelstudio$/, path: path.join(desktopDir, 'services', 'labelStudioPrinting.ts') },
  // Electron / Node leaves -> inert shims (a Worker has no window/fs/printer/SMTP).
  { filter: /^electron$/, path: shim('electron-server.ts') },
  { filter: /^electron\/main$/, path: shim('electron-server.ts') },
  { filter: /^electron-updater$/, path: shim('electron-updater.ts') },
  { filter: /^(\.\.\/logger|\.\/logger)$/, path: shim('logger.ts') },
  { filter: /^\.\.\/generated\/supportKey$/, path: shim('supportKey.ts') },
  { filter: /^\.\/licensing$/, path: shim('licensing.ts') },
  { filter: /^(node:)?fs$/, path: shim('fs.ts') },
  { filter: /^(node:)?os$/, path: shim('os.ts') },
  { filter: /^(node:)?path$/, path: shim('path.ts') },
  { filter: /^(node:)?child_process$/, path: shim('child_process.ts') },
  { filter: /^node:sqlite$/, path: shim('node-sqlite.ts') },
  { filter: /^nodemailer$/, path: shim('nodemailer.ts') },
  { filter: /^xlsx$/, path: shim('xlsx.ts') },
  { filter: /^bwip-js$/, path: shim('bwip-js.ts') },
  { filter: /^pdfkit$/, path: shim('pdfkit.ts') },
  { filter: /^whatsapp-web\.js$/, path: shim('whatsapp-web.ts') },
  { filter: /^qrcode$/, path: shim('qrcode.ts') },
];

// ---------------------------------------------------------------------------
// 2. Bundle the worker.
// ---------------------------------------------------------------------------
const result = await build({
  entryPoints: [path.join(srcDir, 'index.ts')],
  outfile: path.join(root, 'dist', 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  define: { __APP_VERSION__: JSON.stringify(appVersion) },
  sourcemap: false,
  logLevel: 'info',
  plugins: [
    {
      name: 'rokar-pos-cloud-aliases',
      setup(pluginBuild) {
        for (const alias of resolveAliases) {
          pluginBuild.onResolve({ filter: alias.filter }, () => ({ path: alias.path }));
        }
      },
    },
  ],
});

const bytes = result.outputFiles?.[0]?.contents?.byteLength ?? 0;
console.log(`[build] bundle -> dist/index.js (${bytes} bytes)`);